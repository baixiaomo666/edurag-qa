"""
文本预处理工具模块
功能：对用户输入/问题文本进行标准化预处理（小写转换、中文分词、停用词过滤）
为后续检索、匹配提供标准化文本
"""
import jieba
from base.logger import logger

# 中文停用词表（虚词、疑问词、标点）
# 为什么要过滤：BM25 的 IDF 项会给"的/了/是"这类高频虚词很低的权重，
# 但它们仍会占用查询词项、参与文档长度归一化，稀释真正有区分度的实词；
# "什么/如何/请问"这类词在几乎所有问题里都出现，对区分具体问题是纯噪声。
# 注意：只收虚词与标点，不收"课程/专业/考试"这类可能承载语义的名词。
STOPWORDS = {
    # 结构助词与语气词
    "的", "地", "得", "了", "着", "过", "吗", "呢", "吧", "啊", "呀", "嘛",
    # 连词与介词
    "和", "与", "或", "及", "等", "在", "从", "到", "向", "往", "于",
    "而", "但", "如果", "因为", "所以", "以及", "并且", "把", "被", "给", "让", "对",
    # 代词
    "我", "你", "他", "她", "它", "我们", "你们", "他们",
    "这", "那", "这个", "那个", "这些", "那些", "自己",
    # 疑问词与客套词
    "什么", "怎么", "怎样", "如何", "为什么", "哪些", "哪个", "多少", "是否",
    "请问", "一下", "能否", "可以", "有没有",
    # 高频副词与能愿动词
    "就", "都", "也", "还", "很", "更", "最", "会", "要", "能", "需要",
    # 标点与空白
    " ", "\t", "\n", "，", "。", "？", "！", "、", "；", "：", "（", "）",
    "《", "》", "\"", "'", "“", "”", "‘", "’",
    ",", ".", "?", "!", ";", ":", "(", ")", "[", "]", "-", "/", "\\",
}


def process_text(text):
    """
    文本预处理核心函数：统一小写 + jieba 中文分词 + 停用词过滤
    :param text: 原始输入文本
    :return: 分词后的词汇列表，异常时返回空列表
    """
    logger.debug(f"开始文本预处理：{text}")

    try:
        # 文本小写转换 + jieba 精确分词，返回词列表
        tokens = jieba.lcut(text.lower())
        # 过滤停用词与纯空白词项，避免虚词干扰 BM25 打分
        return [t for t in tokens if t.strip() and t not in STOPWORDS]
    except AttributeError as e:
        # 捕获文本为空/非字符串类型等异常
        logger.error(f"文本预处理异常: {e}")
        return []
